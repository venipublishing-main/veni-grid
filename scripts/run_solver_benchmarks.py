"""Execute real search, preserve complete inputs/results, produce a readable proof example."""
from pathlib import Path
import json
from veni_grid_solver import solve

ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'evidence_solver';OUT.mkdir(exist_ok=True)


def run():
    results=[]
    cases=[('school-benchmark-a','FEASIBLE'),('school-teacher-shortage','INFEASIBLE'),
           ('school-double-bottleneck','INFEASIBLE'),('school-locked-clash','INFEASIBLE')]
    for name,expected in cases:
        data=json.loads((ROOT/'fixtures_solver'/f'{name}.json').read_text())
        r=solve(data)
        assert r.status==expected,(name,r.model_dump())
        (OUT/f'{name}-result.json').write_text(r.model_dump_json(indent=2)+'\n')
        results.append({'name':name,'expected':expected,'status':r.status,'solver_status':r.solver_status,
                        'independent_validation':r.validation,'events':len(r.candidate.event_assignments) if r.candidate else 0,
                        'backend_version':r.backend_version,'compilation_ms':r.compilation_ms,'solve_ms':r.solve_ms,
                        'validation_ms':r.validation_ms,'total_ms':r.total_ms,'model_hash':r.model_hash})
        if r.candidate:render_markdown(data,r)
    data=json.loads((ROOT/'fixtures_solver/school-benchmark-a.json').read_text());r=solve(data,{'max_time_seconds':0})
    assert r.status=='UNKNOWN'
    (OUT/'school-zero-budget-result.json').write_text(r.model_dump_json(indent=2)+'\n')
    results.append({'name':'school-zero-budget','expected':'UNKNOWN','status':r.status,'solver_status':r.solver_status,'proven_infeasible':r.proven_infeasible})
    for path in ['fixtures/master_school/problem.json','fixtures/learner_choices/problem.json','fixtures/invigilation/problem.json',
                 'fixtures_v03/F1_shared_capacity/problem.json','fixtures_rc/R1_operational/problem.json',
                 'fixtures_v04/H1_options_to_lessons/handoff.json','fixtures_rc/R3_flexible_options/handoff.json']:
        source=json.loads((ROOT/path).read_text());data=source.get('problem',source)
        data['schema_version']='1.0.0-rc1' # explicit promotion, schema checks still run
        name=Path(path).parent.name
        (OUT/f'{name}-input-promoted.json').write_text(json.dumps(data,indent=2)+'\n')
        r=solve(data);assert r.status=='FEASIBLE' and r.validation=='PASSED',(name,r.findings)
        (OUT/f'{name}-result.json').write_text(r.model_dump_json(indent=2)+'\n')
        results.append({'name':name,'expected':'FEASIBLE','status':r.status,'solver_status':r.solver_status,
                        'independent_validation':r.validation,'events':len(r.candidate.event_assignments),'enrollments':len(r.candidate.enrollment_assignments),
                        'source_input':path,'total_ms':r.total_ms,'model_hash':r.model_hash})
    (OUT/'benchmark-summary.json').write_text(json.dumps(results,indent=2)+'\n')
    print(json.dumps(results,indent=2))
    return results


def render_markdown(p,r):
    # Read-only display built from solved assignments; no placement decisions here.
    from veni_grid_contract.core_v1 import CoreProblem
    from veni_grid_contract.validation import window_placement
    model=CoreProblem.model_validate(p);events={e.id:e for e in model.events}
    slots={w.id:w for w in model.windows};table={}
    for a in r.candidate.event_assignments:
        e=events[a.event_id];day,start,end,work=window_placement(model,e,a.start_window_id)
        role={q.id:q.role for q in e.requirements}
        allocations={role[q.requirement_id]:', '.join(q.resource_ids) for q in a.resource_allocations}
        for group in e.fixed_participant_ids:
            for w in model.windows:
                if w.day_id==day and start<=w.start_minute<end:
                    label=e.label.split()[1]+(' (double)' if e.duration.count>1 else '')
                    table[group,w.day_id,w.sequence]=f'{label}; {allocations.get("ROOM","").replace("room:","")}; {allocations.get("TEACHER","").replace("teacher:","T_")}'
    lines=['# Veni Grid — solver-generated school example','',
           'Synthetic Benchmark A: 24 lesson events, 26 class-periods, two classes, four teachers and three rooms. ',
           'Generated by OR-Tools CP-SAT; independent hard-rule validation PASSED. Not quality-optimised or published.','']
    for group in ['group:G7A','group:G7B']:
        lines += [f'## {group.replace("group:","")}', '', '| Period | '+' | '.join(d.label for d in model.days)+' |', '|---|'+'---|'*len(model.days)]
        for period in range(1,7):lines.append('| '+str(period)+' | '+' | '.join(table.get((group,d.id,period),'—') for d in model.days)+' |')
        lines.append('')
    lines += ['## Scope','', 'Empty cells are deliberately unused in this small synthetic curriculum. A real school dataset must declare its complete required demand.',
              'No preference score, school-scale performance or competitor-parity claim is made.']
    (OUT/'school-benchmark-a-generated.md').write_text('\n'.join(lines)+'\n')

if __name__=='__main__':run()
